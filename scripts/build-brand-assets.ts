export async function prepareBrandAssets() {
  await mkdir(join(root, "assets/flavours"), { recursive: true });
  const wordmark = pathData(await read("assets/brand/wordmark.svg"));
  const symbol = pathData(await read("assets/brand/symbol.svg"));
  await writeFile(join(root, "lib/brand-art.ts"), `// Generated by assets:hero from assets/brand/*.svg.\nexport const wordmarkPath = ${JSON.stringify(wordmark)};\nexport const symbolPath = ${JSON.stringify(symbol)};\n`);
  const template = await read("assets/brand/label-template.svg");
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({ viewport: { width: 2048, height: 1024 } });
    for (const flavour of flavours) {
      const ink = flavour.ink === "polpa" ? "#FAFAF5" : "#3A2A1D";
      const svg = template.replaceAll("{{wordmark}}", wordmark).replaceAll("{{symbol}}", symbol)
        .replaceAll("{{band}}", flavour.slug === "so-o-coco" ? "#FAFAF5" : flavour.accent)
        .replaceAll("{{ink}}", ink).replaceAll("{{name}}", flavour.name)
        .replaceAll("{{ingredients}}", flavour.slug === "so-o-coco" ? "Água de coco, polpa de coco" : `Coco e ${flavour.name.toLowerCase()}`)
        .replaceAll("{{stats}}", `${flavour.kcal} kcal e ${flavour.sugarGrams} g de açúcar`)
        .replaceAll("{{fruit}}", fruit[flavour.slug] ?? '<ellipse cx="100" cy="108" rx="90" ry="78" fill="#6E8F35"/><ellipse cx="100" cy="104" rx="68" ry="56" fill="#FAFAF5"/><ellipse cx="100" cy="102" rx="44" ry="34" fill="#DCE6EA"/>');
      const file = join(root, "assets/flavours", `label-${flavour.slug}.svg`);
      await writeFile(file, svg);
      if (flavour.slug === "so-o-coco") await writeFile(join(root, "assets/hero/label-so-o-coco.svg"), svg);
      await page.goto(pathToFileURL(file).href);
      await page.evaluate(() => document.fonts.ready);
      await page.screenshot({ path: join(work, `label-${flavour.slug}.png`) });
    }
  } finally { await browser.close(); }
  await writeFile(join(work, "flavours.json"), JSON.stringify(flavours.map(f => f.slug)));
}

export async function finishBrandAssets() {
  await mkdir(join(root, "public/flavours"), { recursive: true });
  for (const { slug } of flavours) {
    const stats = await sharp(join(work, `can-${slug}.png`)).stats();
    if (stats.channels.length !== 4 || stats.channels[3].min !== 0 || stats.channels[3].max !== 255) {
      throw new Error(`${slug}: expected transparent background and opaque can`);
    }
    const output = await sharp(join(work, `can-${slug}.png`)).webp({ quality: 85, alphaQuality: 100 }).toBuffer();
    if (output.length > 80 * 1024) throw new Error(`${slug}: card exceeds 80 KiB`);
    await writeFile(join(root, "public/flavours", `${slug}.webp`), output);
    console.log(`${slug}: transparent card ${(output.length / 1024).toFixed(1)} KiB`);
  }
  // Embed raster + paths so the committed sharing SVG is standalone and editable.
  const wordmark = pathData(await read("assets/brand/wordmark.svg"));
  const symbol = pathData(await read("assets/brand/symbol.svg"));
  const can = (await readFile(join(work, "can-so-o-coco.png"))).toString("base64");
  const font = (await readFile(join(root, "assets/hero/fonts/Figtree-wght.ttf"))).toString("base64");
  const sharing = `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630" viewBox="0 0 1200 630">
<defs><style>@font-face{font-family:Figtree;src:url(data:font/ttf;base64,${font})}</style>
<filter id="shadow" x="-20%" y="-20%" width="150%" height="150%"><feFlood flood-color="#3A2A1D"/><feComposite in2="SourceAlpha" operator="in"/><feOffset dx="12" dy="14"/><feMerge><feMergeNode/><feMergeNode in="SourceGraphic"/></feMerge></filter>
<filter id="grain"><feTurbulence type="fractalNoise" baseFrequency=".55" numOctaves="3" stitchTiles="stitch"/><feColorMatrix values="0 0 0 0 .227 0 0 0 0 .165 0 0 0 0 .114 0 0 0 .07 0"/><feBlend in="SourceGraphic" mode="multiply"/></filter></defs>
<path fill="#FAFAF5" filter="url(#grain)" d="M0 0h1200v630H0z"/>
<path fill="#3A2A1D" fill-rule="evenodd" transform="translate(72 178) scale(1.4)" d="${wordmark}"/>
<g fill="#3A2A1D" font-family="Figtree"><text x="76" y="377" font-size="64" font-weight="800">Só o coco.</text><text x="76" y="550" font-size="26" font-weight="600">Marca fictícia.</text></g>
<image href="data:image/png;base64,${can}" x="738" y="52" width="360" height="520" filter="url(#shadow)"/>
</svg>`;
  const icon = `<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 100 100"><path fill="#FAFAF5" d="M0 0h100v100H0z"/><path fill="#3A2A1D" transform="translate(12 12) scale(.76)" d="${symbol}"/></svg>`;
  await writeFile(join(root, "assets/metadata/sharing-image.svg"), sharing);
  await writeFile(join(root, "assets/metadata/icon.svg"), icon);
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({ viewport: { width: 1200, height: 630 } });
    await page.goto(pathToFileURL(join(root, "assets/metadata/sharing-image.svg")).href);
    await page.evaluate(() => document.fonts.ready);
    await page.screenshot({ path: join(root, "public/sharing-image.png") });
  } finally { await browser.close(); }
  const png = await sharp(Buffer.from(icon)).resize(32, 32).png().toBuffer();
  await writeFile(join(root, "app/icon.png"), png);
  await sharp(Buffer.from(icon)).resize(180, 180).png().toFile(join(root, "app/apple-icon.png"));
  // ICO directory with one PNG payload; supported by current browsers and Windows.
  const header = Buffer.alloc(22);
  header.writeUInt16LE(1, 2); header.writeUInt16LE(1, 4);
  header[6] = header[7] = 32;
  header.writeUInt16LE(1, 10); header.writeUInt16LE(32, 12);
  header.writeUInt32LE(png.length, 14); header.writeUInt32LE(22, 18);
  await writeFile(join(root, "app/favicon.ico"), Buffer.concat([header, png]));
}
